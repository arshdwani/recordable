// OSHA forms as data: the Form 301 equivalent (incident report), the Form 300 log rows and the Form 300A summary.
// Equivalent forms are allowed if they hold the same information and are as readable (29 CFR 1904.29(b)(4)).
// Names and narrative are read from the Jira request when a document is generated; Recordable never stores them.
import { fmt, isIsoDate } from './dates.js';
import { BODY_PART, TYPE, TREATMENT, citeText } from './catalog.js';

const yesNo = (v) => (v ? 'Yes' : 'No');
const or = (v, missing = 'Not given on the request') => (v === undefined || v === null || String(v).trim() === '' ? missing : String(v));
const time12 = (t) => {
  if (!/^\d{2}:\d{2}$/.test(t || '')) return null;
  const [h, m] = t.split(':').map(Number);
  return `${((h + 11) % 12) + 1}:${String(m).padStart(2, '0')} ${h < 12 ? 'AM' : 'PM'}`;
};

export const form301Name = (c) => `OSHA-301-${c.log?.caseNo || c.issueKey}-${c.issueKey}.pdf`;

/** Blocks for renderPdf: the Injury and Illness Incident Report, Form 301 equivalent. */
export function form301Blocks({ c, r, est, portal = {}, org = '' }) {
  const f = c.facts || {};
  const privacy = r.privacy?.length > 0;
  const treat = (f.treatments || []).map((t) => TREATMENT[t]?.label).filter(Boolean);
  return [
    { t: 'title', text: 'Injury and Illness Incident Report (OSHA Form 301 equivalent)' },
    { t: 'small', text: `${org ? `${org} · ` : ''}${est?.name || ''}${est?.city ? `, ${est.city}${est.state ? `, ${est.state}` : ''}` : ''} · Jira request ${c.issueKey} · generated by Recordable` },
    { t: 'small', text: 'This form contains information relating to employee health and must be used in a manner that protects the confidentiality of employees to the extent possible while the information is being used for occupational safety and health purposes.' },
    { t: 'h', text: 'Information about the employee' },
    { t: 'kv', rows: [
      ['1) Full name', or(portal.employee)],
      ['   Job title', or(portal.jobTitle)],
      ['2) Street, city, state, ZIP', or(portal.address, 'Complete from HR records')],
      ['3) Date of birth', or(portal.dob && fmt(portal.dob), 'Complete from HR records')],
      ['4) Date hired', or(portal.hired && fmt(portal.hired), 'Complete from HR records')],
      ['5) Sex', or(portal.sex, 'Complete from HR records')],
    ] },
    { t: 'h', text: 'Information about the physician or other health care professional' },
    { t: 'kv', rows: [
      ['6) Name', or(portal.physician)],
      ['7) Facility (if treated away from the worksite)', or(portal.facility, f.hospital === 'er' || f.hospital === 'inpatient' ? 'Not given on the request' : 'Not applicable or not given')],
      ['8) Treated in an emergency room?', yesNo(f.hospital === 'er' || f.hospital === 'inpatient')],
      ['9) Hospitalized overnight as an in-patient?', yesNo(f.hospital === 'inpatient')],
    ] },
    { t: 'h', text: 'Information about the case' },
    { t: 'kv', rows: [
      ['10) Case number from the Log', c.log?.caseNo || 'Not on the log'],
      ['11) Date of injury or illness', isIsoDate(f.incidentDate) ? fmt(f.incidentDate) : 'Not given'],
      ['12) Time employee began work', or(time12(f.startTime), 'Not given')],
      ['13) Time of event', or(time12(f.incidentTime), 'Cannot be determined')],
      ['14) What was the employee doing just before the incident occurred?', or(portal.doing)],
      ['15) What happened? How did the injury occur?', or(portal.happened)],
      ['16) What was the injury or illness? Part of body affected; how it was affected', `${or(portal.injury, '')}${portal.injury ? ' · ' : ''}${BODY_PART[f.bodyPart]?.label || 'Body part not given'} · ${TYPE[r.type]?.label || 'Injury'}`],
      ['17) What object or substance directly harmed the employee?', or(portal.object)],
      ['18) If the employee died, date of death', f.death ? (isIsoDate(f.deathDate) ? fmt(f.deathDate) : 'Date not given') : 'Not applicable'],
    ] },
    { t: 'h', text: 'Recordability (how Recordable decided)' },
    { t: 'p', text: r.summary },
    ...r.steps.filter((s) => ['yes', 'no', 'first-aid', 'privacy', 'note'].includes(s.result)).map((s) => ({ t: 'li', text: `${s.text} (${citeText(s.cite)})` })),
    { t: 'kv', rows: [
      ['Outcome (Form 300 G-J)', `${r.outcomeLabel || '-'}${r.outcomeCol ? ` (column ${r.outcomeCol})` : ''}`],
      ['Days away / restricted', `${r.days?.away || 0} / ${r.days?.restricted || 0}${r.days?.capped ? ' (180-day cap reached)' : ''}`],
      ['Type (Form 300 M)', `${r.typeLabel}${r.typeCol ? ` (column ${r.typeCol})` : ''}`],
      ['Treatment given', treat.length ? treat.join('; ') : 'None recorded'],
      ['Privacy case', privacy ? `Yes: ${r.privacy.map((p) => citeText(p.cite)).join(', ')}. The log shows "Privacy case" instead of the name.` : 'No'],
    ] },
    { t: 'gap' },
    { t: 'box', lines: ['Completed by: ______________________________   Title: ____________________   Phone: ________________   Date: ____________'] },
    { t: 'small', text: 'Keep this report for 5 years following the end of the calendar year it covers (29 CFR 1904.33). Fill it in within 7 calendar days of learning of a recordable case (29 CFR 1904.29(b)(3)).' },
  ];
}

// ---- Form 300: Log of Work-Related Injuries and Illnesses ------------------------------------------------------
export const CONFIDENTIAL = 'Attention: This form contains information relating to employee health and must be used in a manner that protects the confidentiality of employees to the extent possible while the information is being used for occupational safety and health purposes.';

/** Blocks for renderPdf(..., { landscape: true }). */
export function form300Blocks({ est, year, rows, t, org = '' }) {
  const mark = (on) => (on ? 'X' : '');
  return [
    { t: 'title', text: `OSHA's Form 300 (equivalent): Log of Work-Related Injuries and Illnesses, ${year}` },
    { t: 'small', text: `${org ? `${org} · ` : ''}Establishment: ${est.name}${est.city ? ` · ${est.city}` : ''}${est.state ? `, ${est.state}` : ''} · generated by Recordable from Jira Service Management` },
    { t: 'small', text: CONFIDENTIAL },
    {
      t: 'table',
      size: 6.8,
      cols: [
        { title: '(A) Case no.', w: 46 }, { title: "(B) Employee's name", w: 80 }, { title: '(C) Job title', w: 62 }, { title: '(D) Date', w: 32 },
        { title: '(E) Where the event occurred', w: 78 }, { title: '(F) Injury or illness, parts of body, object or substance', w: 150 },
        { title: '(G) Death', w: 26 }, { title: '(H) Days away', w: 28 }, { title: '(I) Transfer or restriction', w: 38 }, { title: '(J) Other', w: 26 },
        { title: '(K) Days away', w: 28 }, { title: '(L) Days transfer or restriction', w: 38 },
        { title: '(M1) Injury', w: 26 }, { title: '(M2) Skin', w: 22 }, { title: '(M3) Resp.', w: 24 }, { title: '(M4) Poison.', w: 26 }, { title: '(M5) Hearing', w: 28 }, { title: '(M6) Other ill.', w: 26 },
      ],
      rows: [
        ...rows.map((r) => [r.caseNo, r.name, r.jobTitle, r.date, r.where, r.describe, mark(r.outcomeCol === 'G'), mark(r.outcomeCol === 'H'), mark(r.outcomeCol === 'I'), mark(r.outcomeCol === 'J'),
          `${r.away}${r.ongoing && r.away ? '+' : ''}`, `${r.restricted}${r.ongoing && r.restricted ? '+' : ''}`, mark(r.typeCol === 'M1'), mark(r.typeCol === 'M2'), mark(r.typeCol === 'M3'), mark(r.typeCol === 'M4'), mark(r.typeCol === 'M5'), mark(r.typeCol === 'M6')]),
        ['', 'Page totals', '', '', '', '', t.G, t.H, t.I, t.J, t.K, t.L, t.M1, t.M2, t.M3, t.M4, t.M5, t.M6],
      ],
    },
    { t: 'small', text: `${rows.length ? '' : 'No recordable cases on this log. '}"+" means the employee is still away or restricted: the count runs until they return (estimate at year end and update later, 29 CFR 1904.7(b)(3)(ix)). Totals stop at 180 days per case (29 CFR 1904.7(b)(3)(vii)). "Privacy case" replaces the name for privacy concern cases; the confidential list of names is kept separately on the Jira requests (29 CFR 1904.29(b)(6)). Keep this log for 5 years after the end of ${year} (29 CFR 1904.33).` },
  ];
}

// ---- Form 300A: Summary of Work-Related Injuries and Illnesses -------------------------------------------------
export function form300ABlocks({ est, year, t, avgEmployees, hours, org = '', rates = null }) {
  const n = (v) => (v === null || v === undefined || v === '' ? '____' : Number(v).toLocaleString('en-US'));
  return [
    { t: 'title', text: `OSHA's Form 300A (equivalent): Summary of Work-Related Injuries and Illnesses, ${year}` },
    { t: 'small', text: 'All establishments covered by Part 1904 must complete this Summary page, even if no work-related injuries or illnesses occurred during the year.' },
    { t: 'small', text: 'Employees, former employees, and their representatives have the right to review the OSHA Form 300 in its entirety. They also have limited access to the OSHA Form 301 or its equivalent. See 29 CFR Part 1904.35, in OSHA\'s recordkeeping rule, for further details on the access provisions for these forms.' },
    { t: 'h', text: 'Number of cases' },
    { t: 'kv', labelWidth: 330, rows: [['(G) Total number of deaths', t.G], ['(H) Total number of cases with days away from work', t.H], ['(I) Total number of cases with job transfer or restriction', t.I], ['(J) Total number of other recordable cases', t.J]] },
    { t: 'h', text: 'Number of days' },
    { t: 'kv', labelWidth: 330, rows: [['(K) Total number of days away from work', t.K], ['(L) Total number of days of job transfer or restriction', t.L]] },
    { t: 'h', text: 'Injury and illness types: total number of' },
    { t: 'kv', labelWidth: 330, rows: [['(M1) Injuries', t.M1], ['(M2) Skin disorders', t.M2], ['(M3) Respiratory conditions', t.M3], ['(M4) Poisonings', t.M4], ['(M5) Hearing loss', t.M5], ['(M6) All other illnesses', t.M6]] },
    { t: 'h', text: 'Establishment information' },
    { t: 'kv', labelWidth: 200, rows: [
      ['Company name', org || est.company || ''], ['Establishment name', est.name], ['Street', est.street || ''], ['City, state, ZIP', [est.city, est.state, est.zip].filter(Boolean).join(', ')],
      ['Industry description', est.industry || ''], ['NAICS', est.naics || ''],
    ] },
    { t: 'h', text: 'Employment information' },
    { t: 'kv', labelWidth: 330, rows: [['Annual average number of employees', n(avgEmployees)], ['Total hours worked by all employees last year', n(hours)]] },
    rates?.trc !== null && rates ? { t: 'small', text: `For reference (not part of the form): total recordable case rate ${rates.trc} and DART rate ${rates.dart} per 100 full-time workers ((H+I+J) or (H+I) x 200,000 / hours).` } : null,
    { t: 'h', text: 'Sign here' },
    { t: 'small', text: 'Knowingly falsifying this document may result in a fine.' },
    { t: 'box', lines: ['I certify that I have examined this document and that to the best of my knowledge the entries are true, accurate, and complete.', ' ', 'Company executive: ______________________________   Title: ______________________', 'Phone: ____________________   Date: ____________'] },
    { t: 'small', text: 'The certifying executive is an owner (sole proprietorship or partnership), an officer of the corporation, the highest ranking company official working at the establishment, or that person\'s immediate supervisor (29 CFR 1904.32(b)(4)).' },
    { t: 'p', text: `Post this Summary page from February 1 to April 30 of the year following the year covered by the form (${year + 1}).` },
  ].filter(Boolean);
}
